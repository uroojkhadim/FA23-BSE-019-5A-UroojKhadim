/// Constants for spacing used throughout the BMI calculator app
class SpacingConstants {
  /// Small spacing (5.0)
  static const double small = 5.0;
  
  /// Medium spacing (10.0)
  static const double medium = 10.0;
  
  /// Large spacing (15.0)
  static const double large = 15.0;
  
  /// Extra large spacing (20.0)
  static const double extraLarge = 20.0;
  
  /// Huge spacing (30.0)
  static const double huge = 30.0;
  
  /// Default padding for app
  static const EdgeInsets defaultPadding = EdgeInsets.all(16.0);
  
  /// Default margin for app
  static const EdgeInsets defaultMargin = EdgeInsets.all(0.0);
  
  /// Padding for input fields
  static const EdgeInsets inputPadding = EdgeInsets.all(20.0);
  
  /// Padding for buttons
  static const EdgeInsets buttonPadding = EdgeInsets.symmetric(horizontal: 30.0, vertical: 15.0);
  
  /// Padding for cards
  static const EdgeInsets cardPadding = EdgeInsets.all(20.0);
  
  /// Margin between elements
  static const EdgeInsets elementMargin = EdgeInsets.symmetric(vertical: 10.0);
}